import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { buildOfflineGuideHtml } from '../src/lib/offlineExport.ts';
import { inspectInteractiveVisual } from '../src/lib/visuals.ts';
import { offlineGuideFixture, NARRATION_SCRIPTS, SOURCE } from '../benchmarks/offline-guide/fixture.mjs';

const output = resolve(process.argv[2] ?? '/private/tmp/code-atlas-offline-guide');
const audioDirectory = process.argv[3] ? resolve(process.argv[3]) : null;
await mkdir(output, { recursive: true });
const revision = offlineGuideFixture();
const before = JSON.stringify(revision);
assert.equal(inspectInteractiveVisual(revision, revision.sections[0]).status, 'available');
const narration = [];
let voiceEvidence = null;
if (audioDirectory) {
  voiceEvidence = JSON.parse(await readFile(join(audioDirectory, 'narration.json'), 'utf8'));
  assert.equal(voiceEvidence.tracks.length, NARRATION_SCRIPTS.length);
  for (const [index, track] of voiceEvidence.tracks.entries()) {
    assert.equal(track.exactText, NARRATION_SCRIPTS[index]);
    assert.equal(track.file, `scene-${index + 1}.wav`);
    const bytes = await readFile(join(audioDirectory, track.file));
    assert.equal(createHash('sha256').update(bytes).digest('hex'), track.sha256);
    narration.push({ chapterRevisionId: revision.revisionId, sectionId: revision.sections[0].sectionId,
      sceneId: revision.sections[0].claims[index].claimId, exactText: track.exactText,
      audio: { mimeType: 'audio/wav', audioBase64: bytes.toString('base64'), cacheHit: false,
        // Fixture fingerprint, not an injected or claimed native cache receipt.
        fingerprint: createHash('sha256').update(`offline-fixture:${voiceEvidence.modelId}:${voiceEvidence.workerSha256}:${track.exactText}`).digest('hex') } });
  }
}
const observations = [];
for (const includeExcerpts of [true, false]) {
  for (const includeNarrationAudio of audioDirectory ? [true, false] : [false]) {
    const result = await buildOfflineGuideHtml([revision], { selectedRevisionIds: [revision.revisionId],
      includeExcerpts, includeNarrationAudio, narrationAudio: narration, exportedAtUnixMs: 1 });
    assert.equal(result.manifest.schemaVersion, 4);
    assert.equal(JSON.stringify(revision), before);
    const ids = [...result.html.matchAll(/\bid="([^"]+)"/gu)].map(match => match[1]);
    assert.equal(new Set(ids).size, ids.length, 'Package IDs must be unique');
    const links = [...result.html.matchAll(/\bhref="([^"]+)"/gu)].map(match => match[1]);
    for (const link of links) assert.ok(link.startsWith('#') && ids.includes(link.slice(1)), 'Every link stays inside the package and resolves');
    assert.doesNotMatch(result.html, /<script\b|<link\b|<iframe\b|<img\b|\bon(?:load|click|error)=/iu);
    assert.match(result.html, /default-src 'none'; style-src 'unsafe-inline'; media-src data:/u);
    assert.equal((result.html.match(/<audio controls/gu) ?? []).length, includeNarrationAudio ? 2 : 0);
    assert.equal((result.html.match(/class="offline-scene"/gu) ?? []).length, 2);
    assert.ok(includeExcerpts || !result.html.includes('name.trim()'));
    for (const asset of result.manifest.assets) {
      let bytes;
      if (asset.kind === 'narrationAudio') bytes = await readFile(join(audioDirectory, `scene-${asset.sceneId.endsWith('1') ? 1 : 2}.wav`));
      else if (asset.kind === 'narrationTranscript') bytes = Buffer.from(NARRATION_SCRIPTS[asset.sceneId.endsWith('1') ? 0 : 1]);
      else if (asset.kind === 'citedExcerpt') bytes = Buffer.from(SOURCE);
      else if (asset.kind === 'typedVisual') bytes = Buffer.from(JSON.stringify(revision.sections[0].visual));
      assert.equal(asset.sha256, createHash('sha256').update(bytes).digest('hex'));
      assert.equal(asset.byteLength, bytes.length);
    }
    const filename = `guide-${includeExcerpts ? 'sources' : 'no-sources'}-${includeNarrationAudio ? 'audio' : 'no-audio'}.html`;
    await writeFile(join(output, filename), result.html);
    observations.push({ filename, sha256: createHash('sha256').update(result.html).digest('hex'), byteLength: Buffer.byteLength(result.html),
      includeExcerpts, includeNarrationAudio, localLinks: links.length, assets: result.manifest.assets });
  }
}
const report = { fixture: 'Explicitly synthetic accepted chapter, not stored in app history or generated by an agent',
  sourceSha256: createHash('sha256').update(SOURCE).digest('hex'), observations, voiceEvidence,
  nativeCacheQualification: false, humanListeningPass: false, browserPlaybackQualification: false };
await writeFile(join(output, 'qualification.json'), `${JSON.stringify(report, null, 2)}\n`);
console.log(JSON.stringify({ output, packages: observations.length, files: observations.map(item => item.filename) }));
